"""Private file storage (blueprint F.6).

Identity and licence documents never sit in a public bucket and are never
served by path. Code reaches them only through this adapter, and people reach
them only through short-lived signed links (see `markx/sellers/service.py`).

Only the local-disk adapter exists. It is for a laptop and for tests. A real
server needs an S3-compatible adapter with its own backups, so the factory
refuses to hand out the local one there instead of quietly using it.
"""

from __future__ import annotations

import re
from pathlib import Path
from typing import Protocol

from markx.core.config import get_config

_SAFE_KEY = re.compile(r"^[a-z0-9]+(?:[/_.-][a-z0-9]+)*$")


class StoredFileMissing(LookupError):
    pass


class PrivateStorage(Protocol):
    def put(self, key: str, data: bytes) -> None: ...

    def get(self, key: str) -> bytes: ...


def _checked(key: str) -> str:
    # Keys are generated by the server; this guards against a mistake ever
    # letting "../" or an absolute path through.
    if not _SAFE_KEY.fullmatch(key) or len(key) > 200:
        raise ValueError(f"unsafe storage key {key!r}")
    return key


class LocalPrivateStorage:
    def __init__(self, root: Path) -> None:
        self._root = root

    def _path(self, key: str) -> Path:
        return self._root / _checked(key)

    def put(self, key: str, data: bytes) -> None:
        path = self._path(key)
        path.parent.mkdir(parents=True, exist_ok=True, mode=0o700)
        path.write_bytes(data)
        path.chmod(0o600)

    def get(self, key: str) -> bytes:
        try:
            return self._path(key).read_bytes()
        except FileNotFoundError as exc:
            raise StoredFileMissing(key) from exc


def get_private_storage() -> PrivateStorage:
    config = get_config()
    if config.is_real_environment:
        raise RuntimeError(
            "no private file storage adapter is configured for a real environment; "
            "the local-disk adapter is for development only"
        )
    return LocalPrivateStorage(config.storage_dir / "private")
