"""File storage behind one interface (blueprint F.6; D-020, D-062, D-090).

Two stores, never one:

- **Private** holds sellers' identity and licence documents, the cleaned
  sources of product pictures and problem photos. Nothing in it is ever
  public. People reach a document or a problem photo only through the API's
  own five-minute link, signed for one signed-in person who must still be
  allowed to see it (`markx/sellers/service.py`, `markx/images/service.py`);
  the API reads the object and answers with its bytes. No bucket address,
  object key or provider link is ever given to a browser for these files.
- **Public** holds rendered product pictures (WebP), served to browsers from
  the CDN's own cookieless domain (`MARKX_PUBLIC_MEDIA_BASE_URL`). MarkX
  never sets an access list on an object: whether the public bucket is
  readable through the CDN is the bucket's own setting.

Adapters, chosen by `MARKX_FILE_STORAGE_PROVIDER`:

- `local`: two folders under `MARKX_STORAGE_DIR`, for a laptop and the tests.
- `minio`, `s3`, `r2`: one S3-compatible adapter (`S3ObjectStore`, on the
  AWS SDK for Python, boto3) with each provider's endpoint, region,
  addressing and encryption. MinIO is the laptop and test stand-in; staging
  and production refuse `local` and `minio` (`markx/core/config.py`).

Every store checks what it is given, whatever the caller already checked:
keys are generated by the server and must match a strict pattern; only
JPEG, PNG and WebP pictures are stored, and the bytes must be what the
declared type says; no object above `MARKX_STORAGE_MAX_OBJECT_BYTES` is
written or read. A provider failure becomes `StorageUnavailable`, a 503 with
no endpoint, bucket, key or credential in it.
"""

