logger = logging.getLogger("markx.storage")

_SAFE_KEY = re.compile(r"^[a-z0-9]+(?:[/_.-][a-z0-9]+)*$")
_MAX_KEY_LENGTH = 200

# Blueprint F.6: "Images only." Nothing else is ever written to either store.
ALLOWED_CONTENT_TYPES = frozenset({"image/jpeg", "image/png", "image/webp"})

# A link straight to an object is never handed to a browser for a private
# file; where one is made at all (operations), it lives five minutes at most,
# as long as the API's own document links (D-020).
MAX_SIGNED_URL_SECONDS = 300

StoreName = Literal["private", "public"]


class StoredFileMissing(LookupError):
    """The object does not exist."""


class StoredFileRefused(ValueError):
    """The store will not hold this: an unsafe key, a type that is not an
    allowed picture, bytes that are not what the type says, or too large."""


class StorageUnavailable(AppError):
    """The store could not be reached or refused the request: unreachable,
    too slow, wrong credentials, a missing bucket. `reason` is for the log
    and for tests; the person sees only that files cannot be handled now."""

    status_code = 503
    code = "storage_unavailable"

    def __init__(self, reason: str) -> None:
        super().__init__(
            "storage_unavailable", "Files cannot be stored or read right now. Please try again."
        )
        self.reason = reason


@dataclass(frozen=True, slots=True)
class StoredObject:
    key: str
    size: int
    content_type: str
    last_modified: datetime | None


class ObjectStore(Protocol):
    """What every adapter offers. `put` overwrites an object with the same
    key; keys are made unique by the caller, so in practice it never does."""

    name: StoreName

    def put(self, key: str, data: bytes, content_type: str) -> None: ...

    def get(self, key: str) -> bytes: ...

    def head(self, key: str) -> StoredObject: ...

    def exists(self, key: str) -> bool: ...

    def delete(self, key: str) -> None: ...

    def signed_url(self, key: str, *, expires_in: int) -> str: ...


# The names the callers have used since D-020 and D-062.
PrivateStorage = ObjectStore
PublicStorage = ObjectStore


# -- checks every store makes ------------------------------------------------------


def checked_key(key: str) -> str:
    """Keys are generated by the server; this guards against a mistake ever
    letting "../", an absolute path or anything unexpected through."""
    if not _SAFE_KEY.fullmatch(key) or len(key) > _MAX_KEY_LENGTH:
        raise StoredFileRefused(f"unsafe storage key {key!r}")
    return key


def sniff_image_type(data: bytes) -> str | None:
    """The picture type the bytes themselves say, from their signature."""
    if data[:3] == b"\xff\xd8\xff":
        return "image/jpeg"
    if data[:8] == b"\x89PNG\r\n\x1a\n":
        return "image/png"
    if len(data) >= 12 and data[:4] == b"RIFF" and data[8:12] == b"WEBP":
        return "image/webp"
    return None


def check_object(key: str, data: bytes, content_type: str, max_bytes: int) -> None:
    checked_key(key)
    if content_type not in ALLOWED_CONTENT_TYPES:
        raise StoredFileRefused(f"content type {content_type!r} is not an allowed picture type")
    if not data:
        raise StoredFileRefused("an empty file is not stored")
    if len(data) > max_bytes:
        raise StoredFileRefused(f"the file is larger than {max_bytes} bytes")
    if sniff_image_type(data) != content_type:
        raise StoredFileRefused(f"the bytes are not a {content_type} picture")


def _check_expiry(expires_in: int) -> int:
    if not 0 < expires_in <= MAX_SIGNED_URL_SECONDS:
        raise ValueError(
            f"a signed link lives between 1 and {MAX_SIGNED_URL_SECONDS} seconds, not {expires_in}"
        )
    return expires_in


# -- local folders: a laptop and the tests ---------------------------------------------


class LocalObjectStore:
    """One folder. Private files are readable by the API's own user only."""

    def __init__(self, root: Path, *, name: StoreName, max_bytes: int = 20_000_000) -> None:
        self._root = root
        self.name: StoreName = name
        self._private = name == "private"
        self._max_bytes = max_bytes

    def _path(self, key: str) -> Path:
        return self._root / checked_key(key)

    def put(self, key: str, data: bytes, content_type: str) -> None:
        check_object(key, data, content_type, self._max_bytes)
        path = self._path(key)
        path.parent.mkdir(parents=True, exist_ok=True, mode=0o700 if self._private else 0o755)
        path.write_bytes(data)
        if self._private:
            path.chmod(0o600)

    def get(self, key: str) -> bytes:
        path = self._path(key)
        try:
            size = path.stat().st_size
            if size > self._max_bytes:
                raise StorageUnavailable("object_too_large")
            return path.read_bytes()
        except FileNotFoundError as exc:
            raise StoredFileMissing(key) from exc

    def head(self, key: str) -> StoredObject:
        path = self._path(key)
        try:
            info = path.stat()
        except FileNotFoundError as exc:
            raise StoredFileMissing(key) from exc
        if not stat.S_ISREG(info.st_mode):
            raise StoredFileMissing(key)
        with path.open("rb") as handle:
            head = handle.read(16)
        return StoredObject(
            key=key,
            size=info.st_size,
            content_type=sniff_image_type(head) or "application/octet-stream",
            last_modified=datetime.fromtimestamp(info.st_mtime, UTC),
        )

    def exists(self, key: str) -> bool:
        return self._path(key).is_file()

    def delete(self, key: str) -> None:
        self._path(key).unlink(missing_ok=True)

    def signed_url(self, key: str, *, expires_in: int) -> str:
        checked_key(key)
        _check_expiry(expires_in)
        raise StorageUnavailable("signed_links_need_object_storage")


class LocalPrivateStorage(LocalObjectStore):
    def __init__(self, root: Path, *, max_bytes: int = 20_000_000) -> None:
        super().__init__(root, name="private", max_bytes=max_bytes)


class LocalPublicStorage(LocalObjectStore):
    """The laptop and test stand-in for the public bucket. Files are served by
    the API's media route, which exists only where dev tools do."""

    def __init__(self, root: Path, *, max_bytes: int = 20_000_000) -> None:
        super().__init__(root, name="public", max_bytes=max_bytes)


# -- S3-compatible object storage: MinIO, Amazon S3, Cloudflare R2 --------------------


@dataclass(frozen=True, slots=True)
class ObjectStorageSettings:
    """Everything one S3-compatible connection needs. Built from `Config` by
    `object_storage_settings`; tests build their own."""

    provider: Literal["minio", "s3", "r2"]
    endpoint_url: str | None
    region: str
    access_key_id: str
    secret_access_key: str
    private_bucket: str
    public_bucket: str
    connect_timeout: float = 5.0
    read_timeout: float = 15.0
    max_bytes: int = 20_000_000
    server_side_encryption: Literal["auto", "AES256", "none"] = "auto"
    # Retries for a request that failed in transit, on top of the first try.
    retries: int = 1

    def __repr__(self) -> str:  # the keys never reach a log or a traceback
        return (
            f"ObjectStorageSettings(provider={self.provider!r}, endpoint_url={self.endpoint_url!r}, "
            f"region={self.region!r}, access_key_id='**********', secret_access_key='**********')"
        )

    @property
    def encryption(self) -> str | None:
        """The `ServerSideEncryption` asked for on every write, if any."""
        if self.server_side_encryption == "AES256":
            return "AES256"
        if self.server_side_encryption == "none":
            return None
        # "auto": S3 encrypts with its own keys when asked; R2 encrypts every
        # object anyway and MinIO needs a key service for it.
        return "AES256" if self.provider == "s3" else None

    @property
    def resolved_endpoint_url(self) -> str:
        if self.endpoint_url:
            return self.endpoint_url
        assert self.provider == "s3", "minio and r2 always name their endpoint"
        return f"https://s3.{self.region}.amazonaws.com"

    @property
    def addressing_style(self) -> Literal["path", "virtual"]:
        # MinIO on a laptop has no wildcard DNS; AWS deprecates path style.
        return "virtual" if self.provider == "s3" else "path"


def object_storage_settings(config: Config) -> ObjectStorageSettings:
    """The S3-compatible settings of a configuration that names one; the
    configuration has already refused missing or malformed values."""
    provider = config.file_storage_provider
    assert provider != "local", "local storage has no object storage settings"
    assert config.storage_access_key_id is not None
    assert config.storage_secret_access_key is not None
    assert config.storage_private_bucket is not None
    assert config.storage_public_bucket is not None
    return ObjectStorageSettings(
        provider=provider,
        endpoint_url=config.storage_endpoint_url,
        region=config.storage_region_name,
        access_key_id=config.storage_access_key_id.get_secret_value(),
        secret_access_key=config.storage_secret_access_key.get_secret_value(),
        private_bucket=config.storage_private_bucket,
        public_bucket=config.storage_public_bucket,
        connect_timeout=config.storage_connect_timeout_seconds,
        read_timeout=config.storage_read_timeout_seconds,
        max_bytes=config.storage_max_object_bytes,
        server_side_encryption=config.storage_server_side_encryption,
    )


def _boto_config(settings: ObjectStorageSettings, *, unsigned: bool = False) -> BotoConfig:
    return BotoConfig(
        signature_version=UNSIGNED if unsigned else "s3v4",
        s3={"addressing_style": settings.addressing_style},
        connect_timeout=settings.connect_timeout,
        read_timeout=settings.read_timeout,
        # "standard" retries throttling and transient errors only, never a
        # refused key or a missing object; the total is bounded so a dead
        # provider fails a request in seconds, not minutes.
        retries={"total_max_attempts": settings.retries + 1, "mode": "standard"},
        # MarkX sends its own Content-MD5 on every write, which S3, R2 and
        # MinIO all check; the newer default checksums are left out because
        # not every S3-compatible service accepts them.
        request_checksum_calculation="when_required",
        response_checksum_validation="when_required",
        max_pool_connections=10,
        user_agent_extra="markx-storage",
    )


def make_s3_client(settings: ObjectStorageSettings, *, unsigned: bool = False) -> S3Client:
    """A client with exactly these credentials, never AWS's credential chain
    (environment, ~/.aws, instance metadata). An anonymous client is given
    placeholder keys it never signs with, so it does not look for any."""
    session = boto3.session.Session(
        aws_access_key_id="anonymous" if unsigned else settings.access_key_id,
        aws_secret_access_key="anonymous" if unsigned else settings.secret_access_key,
        region_name=settings.region,
    )
    # The endpoint is always given, so neither an AWS_ENDPOINT_URL variable nor
    # an ~/.aws/config entry can send MarkX's files anywhere else.
    return session.client(
        "s3",
        endpoint_url=settings.resolved_endpoint_url,
        region_name=settings.region,
        config=_boto_config(settings, unsigned=unsigned),
    )


_MISSING_CODES = frozenset({"NoSuchKey", "404", "NotFound"})


@contextmanager
def _provider_call(store: S3ObjectStore, operation: str) -> Iterator[None]:
    """Turn every provider failure into `StorageUnavailable`, logged with the
    store, the operation and the provider's error code only: no key, bucket,
    endpoint or credential reaches the log or the person."""
    try:
        yield
    except ClientError as exc:
        code = str(exc.response.get("Error", {}).get("Code", "unknown"))
        if code in _MISSING_CODES:
            raise StoredFileMissing(operation) from None
        logger.error(
            "object storage refused a request",
            extra={"store": store.name, "operation": operation, "storage_error": code},
        )
        raise StorageUnavailable(code) from None
    except (ConnectTimeoutError, ReadTimeoutError):
        logger.error(
            "object storage did not answer in time",
            extra={"store": store.name, "operation": operation, "storage_error": "timeout"},
        )
        raise StorageUnavailable("timeout") from None
    except EndpointConnectionError:
        logger.error(
            "object storage could not be reached",
            extra={"store": store.name, "operation": operation, "storage_error": "unreachable"},
        )
        raise StorageUnavailable("unreachable") from None
    except BotoCoreError as exc:
        logger.error(
            "object storage request failed",
            extra={"store": store.name, "operation": operation,
                   "storage_error": type(exc).__name__},
        )  # fmt: skip
        raise StorageUnavailable(type(exc).__name__) from None


class S3ObjectStore:
    """One bucket on an S3-compatible service."""

    def __init__(
        self, client: S3Client, bucket: str, *, name: StoreName, settings: ObjectStorageSettings
    ) -> None:
        self._client = client
        self._bucket = bucket
        self.name: StoreName = name
        self._settings = settings

    @property
    def bucket(self) -> str:
        return self._bucket

    def put(self, key: str, data: bytes, content_type: str) -> None:
        check_object(key, data, content_type, self._settings.max_bytes)
        md5 = hashlib.md5(data, usedforsecurity=False).digest()
        extra: dict[str, Any] = {}
        encryption = self._settings.encryption
        if encryption is not None:
            extra["ServerSideEncryption"] = encryption
        # Rendered pictures never change under their key (D-062); private
        # files are never cached by anything in between.
        cache = "public, max-age=31536000, immutable" if self.name == "public" else "no-store"
        with _provider_call(self, "put"):
            self._client.put_object(
                Bucket=self._bucket,
                Key=key,
                Body=data,
                ContentType=content_type,
                ContentLength=len(data),
                ContentMD5=base64.b64encode(md5).decode("ascii"),
                CacheControl=cache,
                **extra,
            )

    def get(self, key: str) -> bytes:
        checked_key(key)
        with _provider_call(self, "get"):
            response = self._client.get_object(Bucket=self._bucket, Key=key)
            body = response["Body"]
            try:
                if response.get("ContentLength", 0) > self._settings.max_bytes:
                    raise StorageUnavailable("object_too_large")
                data = body.read(self._settings.max_bytes + 1)
            finally:
                body.close()
        if len(data) > self._settings.max_bytes:
            raise StorageUnavailable("object_too_large")
        _check_integrity(self, response.get("ETag"), data)
        return data

    def head(self, key: str) -> StoredObject:
        checked_key(key)
        with _provider_call(self, "head"):
            response = self._client.head_object(Bucket=self._bucket, Key=key)
        return StoredObject(
            key=key,
            size=int(response.get("ContentLength", 0)),
            content_type=str(response.get("ContentType", "application/octet-stream")),
            last_modified=response.get("LastModified"),
        )

    def exists(self, key: str) -> bool:
        try:
            self.head(key)
        except StoredFileMissing:
            return False
        return True

    def delete(self, key: str) -> None:
        """Removes the object; removing one that is not there is not an error.
        No MarkX feature deletes a file today (D-062, D-090)."""
        checked_key(key)
        with _provider_call(self, "delete"):
            self._client.delete_object(Bucket=self._bucket, Key=key)

    def signed_url(self, key: str, *, expires_in: int) -> str:
        """A provider link to one object that works for at most five minutes.
        Anyone holding it can read the object, so it is never given to a
        browser for a private file; documents and problem photos go through
        the API's own links, bound to the signed-in person (D-020, D-090)."""
        checked_key(key)
        with _provider_call(self, "sign"):
            return self._client.generate_presigned_url(
                "get_object",
                Params={"Bucket": self._bucket, "Key": key},
                ExpiresIn=_check_expiry(expires_in),
            )

    def close(self) -> None:
        """Close the connections (shared by the two stores of one settings)."""
        self._client.close()

    # -- for the operations checks (markx/ops/checks.py) ----------------------------

    def check_reachable(self) -> None:
        """Raises `StorageUnavailable` unless the bucket answers with these keys."""
        with _provider_call(self, "check"):
            self._client.head_bucket(Bucket=self._bucket)

    def readable_without_credentials(self, key: str) -> bool:
        """Whether an anonymous request can read this object: it must never
        be possible in the private bucket."""
        checked_key(key)
        anonymous = make_s3_client(self._settings, unsigned=True)
        try:
            anonymous.head_object(Bucket=self._bucket, Key=key)
        except ClientError:
            return False
        except BotoCoreError as exc:
            raise StorageUnavailable(type(exc).__name__) from None
        finally:
            anonymous.close()
        return True


def _check_integrity(store: S3ObjectStore, etag: str | None, data: bytes) -> None:
    """A single-part object's ETag is its MD5 on S3, R2 and MinIO when it is
    not encrypted with a key service; a mismatch means the bytes changed."""
    value = (etag or "").strip('"')
    is_md5 = len(value) == 32 and all(c in "0123456789abcdef" for c in value)
    if is_md5 and hashlib.md5(data, usedforsecurity=False).hexdigest() != value:
        logger.error(
            "object storage returned bytes that do not match their checksum",
            extra={"store": store.name, "operation": "get", "storage_error": "checksum"},
        )
        raise StorageUnavailable("checksum_mismatch")


# -- the stores the application uses -----------------------------------------------------


# Every client `_s3_stores` has built and not yet closed.
_open_clients: list[S3ObjectStore] = []


@lru_cache(maxsize=4)
def _s3_stores(settings: ObjectStorageSettings) -> tuple[S3ObjectStore, S3ObjectStore]:
    """One connection pool per configuration, shared by its two stores."""
    client = make_s3_client(settings)
    private = S3ObjectStore(client, settings.private_bucket, name="private", settings=settings)
    public = S3ObjectStore(client, settings.public_bucket, name="public", settings=settings)
    _open_clients.append(private)
    return private, public


def reset_cached_stores() -> None:
    """Close the cached connections; the next call builds them from the
    configuration again (after a configuration change, and in tests)."""
    _s3_stores.cache_clear()
    while _open_clients:
        _open_clients.pop().close()


def _local_refused(config: Config, which: str) -> None:
    if config.is_real_environment:
        raise RuntimeError(
            f"no {which} file storage adapter is configured for a real environment; "
            "the local-disk adapter is for development only"
        )


def get_private_storage() -> ObjectStore:
    """Documents, picture sources and problem photos (never public)."""
    # PROVISIONAL (F-01, D-083): sellers' identity documents go to a private,
    # encrypted Cloudflare R2 bucket (no public access, five-minute links
    # through the API). The adapter for it now exists (D-090: `r2`, beside
    # `s3`), but no bucket or account does: the founder must choose and
    # create the private document store before going live, and approve in
    # writing before any document is copied there. Nothing here chooses it.
    config = get_config()
    if config.file_storage_provider == "local":
        # Refused here and, since D-090, by the configuration at start-up: a
        # real server never writes a private file to its own disk.
        _local_refused(config, "private")
        return LocalPrivateStorage(
            config.storage_dir / "private", max_bytes=config.storage_max_object_bytes
        )
    return _s3_stores(object_storage_settings(config))[0]


def get_public_storage() -> ObjectStore:
    """Rendered product pictures, served from the CDN (F.6)."""
    config = get_config()
    if config.file_storage_provider == "local":
        _local_refused(config, "public")
        return LocalPublicStorage(
            config.storage_dir / "public", max_bytes=config.storage_max_object_bytes
        )
    return _s3_stores(object_storage_settings(config))[1]


def public_url(key: str) -> str:
    """The address a browser loads a public file from (F.6: in production a
    separate cookieless domain; on a laptop the API's media route)."""
    return f"{get_config().public_media_base_url.rstrip('/')}/{checked_key(key)}"
